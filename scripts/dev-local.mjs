import { spawn } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { createServer } from 'node:net';
import { resolve } from 'node:path';
import { parseEnv } from 'node:util';
process.chdir(resolve(import.meta.dirname, '..'));
if (!existsSync('.env')) throw new Error('Run npm run setup:local first.');
const env = parseEnv(readFileSync('.env', 'utf8'));
if (env.APP_ORIGIN !== 'http://localhost:5175' || env.HOST !== '127.0.0.1' || env.PORT !== '8082')
  throw new Error(
    'dev:local expects the local member configuration produced by setup:local; existing .env was preserved.',
  );
for (const [port, host] of [
  [5175, '127.0.0.1'],
  [5175, 'localhost'],
  [8082, '127.0.0.1'],
]) {
  await new Promise((resolve, reject) => {
    const probe = createServer();
    probe.once('error', () =>
      reject(
        new Error(
          `Local port ${port} is occupied. Stop its owner or use your custom development commands; no process was stopped.`,
        ),
      ),
    );
    probe.listen(port, host, () => probe.close(resolve));
  });
}
const children = [];
let stopping = false;
function stop(code) {
  if (stopping) return;
  stopping = true;
  process.exitCode = code;
  for (const child of children) {
    child.kill('SIGTERM');
  }
  const timeout = setTimeout(() => {
    for (const child of children) {
      if (child.exitCode === null && child.signalCode === null) child.kill('SIGKILL');
    }
  }, 5000);
  timeout.unref();
}
for (const args of [
  ['--env-file=.env', '--import', 'tsx', '--watch', 'src/server/main.ts'],
  ['node_modules/vite/bin/vite.js', '--host', 'localhost', '--port', '5175', '--strictPort'],
]) {
  // Stay in the calling terminal's process group so Ctrl-C/session shutdown also
  // reaches the watcher's child. Only processes started here receive .kill().
  const child = spawn(process.execPath, args, { stdio: 'inherit' });
  children.push(child);
  child.once('error', (error) => {
    console.error(error.message);
    stop(1);
  });
  child.once('exit', (code) => {
    if (!stopping) stop(code || 1);
  });
}
for (const signal of ['SIGINT', 'SIGTERM']) process.once(signal, () => stop(0));
console.log(
  'ANQ Blog local member workspace: http://localhost:5175\nCredentials: .local/member-credentials.json (if generated by setup). PostgreSQL persists when development servers stop.',
);
